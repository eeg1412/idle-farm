export function introLines(gender) {
  return gender === 'male' ? intro.male : intro.female;
}

export function taskExplanation(taskId, gender) {
  const entry = tasks[taskId];
  if (!entry) return null;
  return gender === 'male' ? entry.male : entry.female;
}

